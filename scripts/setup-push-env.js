#!/usr/bin/env node
/**
 * Setup VAPID keys and print Vercel env commands.
 * Run: node scripts/setup-push-env.js
 */
const { execSync } = require("child_process");
const { readFileSync, writeFileSync } = require("fs");
const { join } = require("path");

const root = join(__dirname, "..");
const webDir = join(root, "apps", "web");
const envPath = join(webDir, ".env");

function main() {
  console.log("Generating VAPID keys...\n");
  const out = execSync("npx web-push generate-vapid-keys", {
    cwd: webDir,
    encoding: "utf8",
  });

  const pubMatch = out.match(/Public Key:\s*\n(.+)/);
  const privMatch = out.match(/Private Key:\s*\n(.+)/);
  const publicKey = pubMatch?.[1]?.trim() ?? "";
  const privateKey = privMatch?.[1]?.trim() ?? "";

  if (!publicKey || !privateKey) {
    console.error("Could not parse VAPID keys from output.");
    process.exit(1);
  }

  let envContent = "";
  try {
    envContent = readFileSync(envPath, "utf8");
  } catch {
    envContent = readFileSync(join(webDir, ".env.example"), "utf8");
  }

  const vapidSection = `
# Web Push VAPID (generated by scripts/setup-push-env.js)
VITE_VAPID_PUBLIC_KEY=${publicKey}
VAPID_PRIVATE_KEY=${privateKey}
`.trim();

  if (envContent.includes("VITE_VAPID_PUBLIC_KEY=")) {
    envContent = envContent.replace(
      /VITE_VAPID_PUBLIC_KEY=.*/,
      `VITE_VAPID_PUBLIC_KEY=${publicKey}`
    );
  } else {
    envContent += `\n${vapidSection}\n`;
  }
  if (envContent.includes("VAPID_PRIVATE_KEY=")) {
    envContent = envContent.replace(
      /VAPID_PRIVATE_KEY=.*/,
      `VAPID_PRIVATE_KEY=${privateKey}`
    );
  } else if (!envContent.includes("VAPID_PRIVATE_KEY=")) {
    envContent = envContent.replace(
      /VITE_VAPID_PUBLIC_KEY=.*/,
      `VITE_VAPID_PUBLIC_KEY=${publicKey}\nVAPID_PRIVATE_KEY=${privateKey}`
    );
  }

  writeFileSync(envPath, envContent);
  console.log("✓ Updated apps/web/.env with VAPID keys.\n");
  console.log("Add these to Vercel (Project → Settings → Environment Variables):\n");
  console.log(`  VITE_VAPID_PUBLIC_KEY  = ${publicKey}`);
  console.log(`  VAPID_PRIVATE_KEY      = ${privateKey}\n`);
  console.log("Or via CLI:\n");
  console.log(`  cd apps/web && vercel env add VITE_VAPID_PUBLIC_KEY production`);
  console.log(`  # paste: ${publicKey}`);
  console.log(`  vercel env add VAPID_PRIVATE_KEY production`);
  console.log(`  # paste: ${privateKey}\n`);
}

main();
